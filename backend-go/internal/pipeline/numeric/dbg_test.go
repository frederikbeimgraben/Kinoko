import "testing"

func TestDbg(t *testing.T) {
	a := []float64{0.8564916714362436, 2.368105065960997, 8.012744652063969, 5.821620360643678, 0.9412864224039919, 4.331269402364738, 4.79051298140834, 1.5973891463707857, 7.345771514092146, 1.136720199214034, 3.9122819049566204, 5.167401826213637}
	buf := make([]float64, 16)
	copy(buf[2:], a)
	out := make([]float64, 12)
	uniformLine(out, buf, 5)
	want := []float64{2.2474682778922417, 3.411792350020977, 3.600049634501775, 4.295005180687474, 4.7794867637769425, 3.496415662638306, 3.8012458933279993, 3.8403326486900076, 3.7565351492083843, 3.8319129181694436, 3.512435088895286, 2.043280786076857}
	for i := range out {
		t.Logf("%v %v %v", out[i], want[i], out[i]-want[i])
	}
}
