package photos

import "testing"

// The values come from coarse() of the old service.
func TestCoarseMatchesTheOldService(t *testing.T) {
	cases := [][4]float64{
		{13.411, 52.523, 13.40618535749036, 52.52425440172476},
		{0.0, 0.0, 0.0, 0.0},
		{-3.7, 40.4, -3.7037843253684466, 40.39705353934603},
		{151.2, -33.9, 151.19945257210483, -33.902263744160976},
		{9.17, 48.78, 9.174307845141318, 48.778296802012214},
		{-63.4202, -62.14885, -63.427212312814724, -62.14516708587855},
		{54.33641, -76.10634, 54.352499401296605, -76.10492274523895},
		{12.91752, -23.90737, 12.921095819922982, -23.904060366510958},
		{-159.12039, 1.32356, -159.124186027024, 1.3205174272367948},
		{-166.50156, -11.81107, -166.4977513222831, -11.812791951131873},
		{-154.85205, -72.85308, -154.84569157357922, -72.85303629177147},
		{-27.17309, 58.17968, -27.177722386206906, 58.183614804168165},
		{-135.43129, -49.26346, -135.4247442192863, -49.26338483650736},
		{45.87596, 79.69219, 45.87216428728575, 79.68918433345311},
		{27.75706, -18.39088, 27.755696914809235, -18.388429752066116},
		{171.45184, -80.70828, 171.4536249252234, -80.70427596119296},
		{129.04865, -37.44955, 129.053067015178, -37.45059288537549},
		{-128.06817, -68.03298, -128.0710103232289, -68.02910528206971},
		{-68.94654, 56.27049, -68.94942570581235, 56.2702120014373},
		{-114.9385, 14.52483, -114.93880999363272, 14.525691699604742},
	}
	for _, c := range cases {
		if lon, lat := coarse(c[0], c[1], 1.0); lon != c[2] || lat != c[3] {
			t.Errorf("coarse(%v, %v) = %v, %v; want %v, %v", c[0], c[1], lon, lat, c[2], c[3])
		}
	}
}
